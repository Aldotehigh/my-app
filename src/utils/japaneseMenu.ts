export function japaneseMenuName(name: string): string {
  const suffix = name.match(/^(.*?)\s*\((media orden|corte delgado|corte grueso|copa|botella)\)$/i);
  if (suffix) return japaneseMenuName(suffix[1]) + '（' + suffixes[suffix[2].toLowerCase()] + '）';
  return names[name.trim().toLowerCase()] ?? name;
}
